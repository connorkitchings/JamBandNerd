-- Split product-facing prediction storage into live next-show tables and
-- retained completed-show tables.

create table if not exists public.next_show_prediction_runs (
    id bigint not null generated by default as identity,
    created_at timestamptz not null default now(),
    band text not null,
    model_slug text not null,
    model_version text not null,
    target_show_key text not null,
    target_show_date date not null,
    reference_date date not null,
    generated_at timestamptz not null,
    top_k integer not null,
    predictions jsonb not null,
    constraint next_show_prediction_runs_pkey primary key (id),
    constraint next_show_prediction_runs_context_key
        unique (band, model_slug, model_version, target_show_key),
    constraint next_show_prediction_runs_top_k_positive check (top_k > 0)
);

create index if not exists next_show_prediction_runs_band_model_generated_idx
    on public.next_show_prediction_runs (
        band,
        model_slug,
        model_version,
        generated_at desc
    );

create table if not exists public.next_show_prediction_songs (
    id bigint not null generated by default as identity,
    created_at timestamptz not null default now(),
    prediction_run_id bigint,
    band text not null,
    model_slug text not null,
    model_version text not null,
    target_show_key text not null,
    target_show_date date not null,
    reference_date date not null,
    generated_at timestamptz not null,
    rank integer not null,
    song_name text not null,
    top_k integer not null,
    prediction_payload jsonb not null,
    constraint next_show_prediction_songs_pkey primary key (id),
    constraint next_show_prediction_songs_run_fkey
        foreign key (prediction_run_id)
        references public.next_show_prediction_runs (id)
        on delete cascade,
    constraint next_show_prediction_songs_context_rank_key
        unique (band, model_slug, model_version, target_show_key, rank),
    constraint next_show_prediction_songs_rank_positive check (rank > 0),
    constraint next_show_prediction_songs_top_k_positive check (top_k > 0)
);

create index if not exists next_show_prediction_songs_band_model_rank_idx
    on public.next_show_prediction_songs (
        band,
        model_slug,
        model_version,
        target_show_date asc,
        rank asc
    );

create table if not exists public.completed_show_prediction_runs (
    id bigint not null generated by default as identity,
    created_at timestamptz not null default now(),
    band text not null,
    model_slug text not null,
    model_version text not null,
    target_show_key text not null,
    target_show_date date not null,
    reference_date date not null,
    generated_at timestamptz not null,
    actual_songs jsonb not null,
    actual_song_count integer not null,
    top_k integer not null,
    predictions jsonb not null,
    constraint completed_show_prediction_runs_pkey primary key (id),
    constraint completed_show_prediction_runs_context_key
        unique (band, model_slug, model_version, target_show_key),
    constraint completed_show_prediction_runs_actual_song_count_positive
        check (actual_song_count > 0),
    constraint completed_show_prediction_runs_top_k_positive check (top_k > 0)
);

create index if not exists completed_show_prediction_runs_band_model_target_idx
    on public.completed_show_prediction_runs (
        band,
        model_slug,
        model_version,
        target_show_date desc
    );

create table if not exists public.completed_show_accuracy (
    id bigint not null generated by default as identity,
    created_at timestamptz not null default now(),
    band text not null,
    model_slug text not null,
    model_version text not null,
    show_id text not null,
    target_show_key text not null,
    show_date date not null,
    target_show_date date not null,
    reference_date date not null,
    prediction_run_id bigint,
    actual_song_count integer not null,
    evaluated_at timestamptz not null,
    k10_hit integer not null,
    k10_matches integer not null,
    k10_precision double precision not null,
    k10_recall double precision not null,
    k10_f1 double precision not null,
    k25_hit integer not null,
    k25_matches integer not null,
    k25_precision double precision not null,
    k25_recall double precision not null,
    k25_f1 double precision not null,
    k50_hit integer not null,
    k50_matches integer not null,
    k50_precision double precision not null,
    k50_recall double precision not null,
    k50_f1 double precision not null,
    constraint completed_show_accuracy_pkey primary key (id),
    constraint completed_show_accuracy_run_fkey
        foreign key (prediction_run_id)
        references public.completed_show_prediction_runs (id)
        on delete cascade,
    constraint completed_show_accuracy_context_key
        unique (band, model_slug, model_version, target_show_key)
);

create index if not exists completed_show_accuracy_band_model_date_idx
    on public.completed_show_accuracy (
        band,
        model_slug,
        model_version,
        show_date desc
    );

alter table public.next_show_prediction_runs enable row level security;
alter table public.next_show_prediction_songs enable row level security;
alter table public.completed_show_prediction_runs enable row level security;
alter table public.completed_show_accuracy enable row level security;

create policy next_show_prediction_runs_public_read
    on public.next_show_prediction_runs for select to anon using (true);
create policy next_show_prediction_songs_public_read
    on public.next_show_prediction_songs for select to anon using (true);
create policy completed_show_prediction_runs_public_read
    on public.completed_show_prediction_runs for select to anon using (true);
create policy completed_show_accuracy_public_read
    on public.completed_show_accuracy for select to anon using (true);

create policy next_show_prediction_runs_service_all
    on public.next_show_prediction_runs for all to service_role
    using (true) with check (true);
create policy next_show_prediction_songs_service_all
    on public.next_show_prediction_songs for all to service_role
    using (true) with check (true);
create policy completed_show_prediction_runs_service_all
    on public.completed_show_prediction_runs for all to service_role
    using (true) with check (true);
create policy completed_show_accuracy_service_all
    on public.completed_show_accuracy for all to service_role
    using (true) with check (true);
