create table if not exists public.historical_prediction_runs (
    id bigint not null generated by default as identity,
    created_at timestamp with time zone not null default now(),
    band text not null,
    model_slug text not null,
    model_version text not null,
    run_type text not null default 'backtest',
    reference_date date not null,
    target_show_id text not null,
    target_show_date date not null,
    generated_at timestamp with time zone not null,
    actual_songs jsonb not null,
    actual_song_count integer not null,
    top_k integer not null,
    predictions jsonb not null,
    constraint historical_prediction_runs_pkey primary key (id),
    constraint historical_prediction_runs_context_key
        unique (band, model_slug, model_version, reference_date, target_show_id),
    constraint historical_prediction_runs_run_type_check
        check (run_type in ('backtest', 'live')),
    constraint historical_prediction_runs_actual_song_count_positive
        check (actual_song_count > 0),
    constraint historical_prediction_runs_top_k_positive check (top_k > 0)
);

create index if not exists historical_prediction_runs_band_model_target_show_date_idx
    on public.historical_prediction_runs (
        band,
        model_slug,
        model_version,
        target_show_date desc
    );

create index if not exists historical_prediction_runs_band_model_reference_date_idx
    on public.historical_prediction_runs (
        band,
        model_slug,
        model_version,
        reference_date desc
    );

alter table public.accuracy_per_show
    add column if not exists prediction_run_id bigint;

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'accuracy_per_show_prediction_run_id_fkey'
    ) then
        alter table public.accuracy_per_show
            add constraint accuracy_per_show_prediction_run_id_fkey
            foreign key (prediction_run_id)
            references public.historical_prediction_runs (id)
            on delete set null;
    end if;
end $$;

create index if not exists accuracy_per_show_prediction_run_id_idx
    on public.accuracy_per_show (prediction_run_id);
