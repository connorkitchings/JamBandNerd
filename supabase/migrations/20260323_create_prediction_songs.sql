create table if not exists public.prediction_songs (
    id bigint not null generated by default as identity,
    created_at timestamp with time zone not null default now(),
    band text not null,
    model_slug text not null,
    model_version text not null,
    reference_date date not null,
    predicted_at timestamp with time zone not null,
    rank integer not null,
    song_name text not null,
    top_k integer not null,
    prediction_payload jsonb not null,
    constraint prediction_songs_pkey primary key (id),
    constraint prediction_songs_band_model_version_reference_date_rank_key
        unique (band, model_version, reference_date, rank),
    constraint prediction_songs_rank_positive check (rank > 0),
    constraint prediction_songs_top_k_positive check (top_k > 0)
);

create index if not exists prediction_songs_band_model_slug_model_version_reference_date_rank_idx
    on public.prediction_songs (band, model_slug, model_version, reference_date desc, rank asc);

create index if not exists prediction_songs_band_model_slug_predicted_at_idx
    on public.prediction_songs (band, model_slug, predicted_at desc);
